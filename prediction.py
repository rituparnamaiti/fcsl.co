import streamlit as st
import pandas as pd
import re
from sklearn.ensemble import RandomForestClassifier
from sklearn.preprocessing import LabelEncoder

# =========================
# LOAD DATA
# =========================
@st.cache_data
def load_data():
    df = pd.read_csv("data-ori.csv")
    df.columns = df.columns.str.upper()

    # CREATE DISEASE COLUMN IF NOT EXISTS
    if "DISEASE" not in df.columns:
        def label_disease(row):
            if row.get("HAEMOGLOBIN", 0) < 12:
                return "Anemia"
            elif row.get("TSH", 0) > 4:
                return "Thyroid"
            else:
                return "Normal"
        df["DISEASE"] = df.apply(label_disease, axis=1)

    # ENCODE DISEASE
    le = LabelEncoder()
    df["DISEASE"] = le.fit_transform(df["DISEASE"])

    # HANDLE SEX
    if "SEX" in df.columns:
        df = pd.get_dummies(df, columns=["SEX"])

    return df, le

df, label_encoder = load_data()

# =========================
# MODEL 1 → IN / OUT
# =========================
X1 = df.drop("SOURCE", axis=1)
y1 = df["SOURCE"]

# =========================
# MODEL 2 → DISEASE
# =========================
X2 = df.drop(["SOURCE", "DISEASE"], axis=1)
y2 = df["DISEASE"]

X1_cols = X1.columns
X2_cols = X2.columns

# =========================
# TRAIN MODELS
# =========================
@st.cache_resource
def train_models():
    model_status = RandomForestClassifier()
    model_disease = RandomForestClassifier()

    model_status.fit(X1, y1)
    model_disease.fit(X2, y2)

    return model_status, model_disease

model_status, model_disease = train_models()

# =========================
# EXTRACT FEATURES
# =========================
def extract_features(text):
    def find(pattern):
        match = re.search(pattern, text.lower())
        try:
            return float(match.group(1)) if match else 0
        except:
            return 0

    sex = "M" if "male" in text.lower() else "F"

    return {
        "HAEMATOCRIT": find(r"haematocrit\\s*([\\d.]+)"),
        "HAEMOGLOBIN": find(r"haemoglobin\\s*([\\d.]+)"),
        "ERYTHROCYTE": find(r"erythrocyte\\s*([\\d.]+)"),
        "LEUCOCYTE": find(r"leucocyte\\s*([\\d.]+)"),
        "THROMBOCYTE": find(r"thrombocyte\\s*([\\d.]+)"),
        "MCH": find(r"mch\\s*([\\d.]+)"),
        "MCHC": find(r"mchc\\s*([\\d.]+)"),
        "MCV": find(r"mcv\\s*([\\d.]+)"),
        "TSH": find(r"tsh\\s*([\\d.]+)"),
        "AGE": find(r"(\\d+)\\s*year"),
        "SEX": sex
    }

# =========================
# PREDICTION PIPELINE
# =========================
def predict_pipeline(data):
    df_input = pd.DataFrame([data])
    df_input = pd.get_dummies(df_input)

    # STEP 1: IN / OUT
    df1 = df_input.reindex(columns=X1_cols, fill_value=0)
    status = model_status.predict(df1)[0]

    # STEP 2: DISEASE if IN
    if str(status).upper() == "IN":
        df2 = df_input.reindex(columns=X2_cols, fill_value=0)
        disease_encoded = model_disease.predict(df2)[0]
        disease = label_encoder.inverse_transform([disease_encoded])[0]
        return status, disease
    else:
        return status, None

# =========================
# UI
# =========================
st.set_page_config(page_title="Patient Chatbot", page_icon="🩺")
st.title("🩺 Patient Diagnosis Chatbot")

if "messages" not in st.session_state:
    st.session_state.messages = []

user_input = st.chat_input("Enter patient details...")

if not user_input:
    st.info("Example: Patient is 25 year old male with haemoglobin 8.5, tsh 6.2")

if user_input:
    if user_input.strip().lower() in ["exit", "quit", "stop"]:
        st.session_state.messages.append({
            "role": "assistant",
            "content": "👋 Chat ended. Refresh page to start again."
        })
        st.stop()

    st.session_state.messages.append({"role": "user", "content": user_input})

    try:
        features = extract_features(user_input)
        status, disease = predict_pipeline(features)

        if str(status).upper() == "IN":
            bot_response = f"🩺 Status: IN\\n🧾 Disease: **{disease}**"
        else:
            bot_response = "🟢 Status: OUT (No disease detected)"

    except Exception as e:
        bot_response = f"⚠️ Error: {str(e)}"

    st.session_state.messages.append({"role": "assistant", "content": bot_response})

for msg in st.session_state.messages:
    with st.chat_message(msg["role"]):
        st.markdown(msg["content"])
