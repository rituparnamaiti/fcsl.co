import pandas as pd
import transformers
from datasets import Dataset
from transformers import AutoTokenizer, AutoModelForCausalLM, Trainer, TrainingArguments, BitsAndBytesConfig
from peft import LoraConfig, get_peft_model
import torch

# 1. Load CSV with pandas
df = pd.read_csv("data-ori.csv")

# 2. Convert to instruction format (your function)
def convert_to_text(row):
    return {
        "text": f"""### Instruction:
Predict whether patient is in or out

### Input:
Haematocrit {row['HAEMATOCRIT']}, Haemoglobin {row['HAEMOGLOBINS']},
Erythrocyte {row['ERYTHROCYTE']}, Leucocyte {row['LEUCOCYTE']},
Thrombocyte {row['THROMBOCYTE']}, MCH {row['MCH']},
MCHC {row['MCHC']}, MCV {row['MCV']}, Age {row['AGE']}, Sex {row['SEX']}

### Response:
{row['SOURCE']}"""
    }

data = [convert_to_text(row) for _, row in df.iterrows()]

# 3. Convert to Hugging Face Dataset
dataset = Dataset.from_list(data)

# 4. Load tokenizer
tokenizer = AutoTokenizer.from_pretrained("TinyLlama/TinyLlama-1.1B-Chat-v1.0")
tokenizer.pad_token = tokenizer.eos_token

# 5. Tokenize
def tokenize(example):
    tokens = tokenizer(
        example["text"],
        truncation=True,
        padding="max_length",
        max_length=128
    )
    tokens["labels"] = tokens["input_ids"].copy()
    return tokens

dataset = dataset.map(tokenize, remove_columns=["text"])

# 6. Format
dataset.set_format(
    type="torch",
    columns=["input_ids", "attention_mask", "labels"]
)

# 7. Load model with 4-bit quantization
bnb_config = BitsAndBytesConfig(
    load_in_4bit=True,
    bnb_4bit_use_double_quant=True,
    bnb_4bit_quant_type="nf4",
    bnb_4bit_compute_dtype=torch.bfloat16
)

model = AutoModelForCausalLM.from_pretrained(
    "TinyLlama/TinyLlama-1.1B-Chat-v1.0",
    quantization_config=bnb_config,
    device_map="auto"
)


# 8. Apply LoRA
lora_config = LoraConfig(
    r=8,
    lora_alpha=16,
    target_modules=["q_proj", "v_proj", "k_proj", "o_proj", "gate_proj", "up_proj", "down_proj"], # Add more target modules for better performance
    lora_dropout=0.05,
    bias="none",
    task_type="CAUSAL_LM"
)

model = get_peft_model(model, lora_config)

# 9. Training arguments
training_args = TrainingArguments(
    output_dir="./results",
    per_device_train_batch_size=2,
    gradient_accumulation_steps=2,
    num_train_epochs=1,
    logging_steps=10,
    save_steps=100,
    fp16=True,
    report_to="none"
)

# 10. Trainer
trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=dataset
)

# 11. Train
trainer.train()

# 12. Save model
model.save_pretrained("./lora_model")
tokenizer.save_pretrained("./lora_model")

